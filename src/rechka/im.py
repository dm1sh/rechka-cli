from . import __version__, paths
from .config import Config

FRAMEWORK_IBUS = "ibus"
FRAMEWORK_FCITX5 = "fcitx5"
FRAMEWORK_NONE = "none"

IBUS_COMPONENT_NAME = "org.freedesktop.IBus.Rechka"
IBUS_ENGINE_NAME = "rechka"
IBUS_GNOME_SERVICE = "org.freedesktop.IBus.session.GNOME.service"
_SYSTEM_COMPONENT_DIR = Path("/usr/share/ibus/component")
_GI_PROBE = (
    "import gi; gi.require_version('IBus', '1.0'); "
    "from gi.repository import IBus"
)


@dataclass
class Detection:
    framework: str  # ibus | fcitx5 | none
    evidence: str


def _running_processes() -> set[str]:
    """Process names from /proc (Linux); empty set elsewhere."""
    names: set[str] = set()
    proc = Path("/proc")
    try:
        entries = list(proc.iterdir())
    except OSError:
        return names
    for entry in entries:
        if not entry.name.isdigit():
            continue
        try:
            names.add((entry / "comm").read_text(encoding="utf-8", errors="replace").strip())
        except OSError:
            continue
    return names


def detect_framework(cfg: Config) -> Detection:
    """Which IM framework this session uses (config override wins)."""
    if cfg.im.framework != "auto":
        return Detection(cfg.im.framework, "config im.framework")

    # Explicit environment hints from the session are the strongest signal.
    xmodifiers = os.environ.get("XMODIFIERS", "")
    gtk_im = os.environ.get("GTK_IM_MODULE", "")
    qt_im = os.environ.get("QT_IM_MODULE", "")
    for hint in (xmodifiers, gtk_im, qt_im):
        lowered = hint.lower()
        if "fcitx" in lowered:
            return Detection(FRAMEWORK_FCITX5, f"environment ({hint!r})")
        if "ibus" in lowered:
            return Detection(FRAMEWORK_IBUS, f"environment ({hint!r})")
    if os.environ.get("IBUS_ADDRESS"):
        return Detection(FRAMEWORK_IBUS, "IBUS_ADDRESS is set")

    # Fall back to what is actually running for this user.
    processes = _running_processes()
    if "fcitx5" in processes or "fcitx" in processes:
        return Detection(FRAMEWORK_FCITX5, "fcitx5 process is running")
    if "ibus-daemon" in processes:
        return Detection(FRAMEWORK_IBUS, "ibus-daemon process is running")
    return Detection(FRAMEWORK_NONE, "no ibus/fcitx5 detected")


@dataclass
class EngineStatus:
    framework: str
    started: bool
    detail: str
    pid: int | None = None
    process: object = field(default=None, repr=False, compare=False)


@dataclass
class IBusInstallResult:
    component_path: Path
    launcher_path: Path | None
    dropin_path: Path | None
    exec_command: str


def _package_parent() -> Path:
    return Path(__file__).resolve().parent.parent


def ibus_component_dir(system: bool = False) -> Path:
    if system:
        return _SYSTEM_COMPONENT_DIR
    return paths.data_home() / "ibus" / "component"


def ibus_component_path(system: bool = False) -> Path:
    return ibus_component_dir(system) / "rechka.xml"


def ibus_launcher_path() -> Path:
    return paths.data_home() / "rechka" / "ibus-engine"


def ibus_dropin_path() -> Path:
    return (
        paths.config_home()
        / "systemd"
        / "user"
        / f"{IBUS_GNOME_SERVICE}.d"
        / "rechka.conf"
    )


def launcher_text(
    package_parent: Path | None = None, *, exec_by_ibus: bool = True
) -> str:
    """Standalone engine launcher for the distro /usr/bin/python3.

    The IBus engine itself needs only the standard library plus
    PyGObject, so it can run under the distro Python (which is where
    python3-gobject / python3-gi live) even when rechka itself runs in a
    uv venv without PyGObject.  The launcher points that Python at the
    directory containing the installed ``rechka`` package.
    """
    parent = package_parent or _package_parent()
    return (
        "#!/usr/bin/python3\n"
        '"""Rechka IBus engine launcher (generated by `rechka im install`)."""\n'
        "import sys\n"
        f"sys.path.insert(0, {str(parent)!r})\n"
        "from pathlib import Path\n"
        "from rechka.config import load_config\n"
        "from rechka.ibus_engine import run\n\n"
        'if __name__ == "__main__":\n'
        '    _cfg_path = sys.argv[1] if len(sys.argv) > 1 else ""\n'
        "    raise SystemExit(\n"
        f"        run(load_config(Path(_cfg_path) if _cfg_path else None), exec_by_ibus={exec_by_ibus!r})\n"
        "    )\n"
    )


def write_ibus_launcher(
    target: Path | None = None, *, exec_by_ibus: bool = True
) -> Path:
    target = target or ibus_launcher_path()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(launcher_text(exec_by_ibus=exec_by_ibus), encoding="utf-8")
    target.chmod(0o755)
    return target


def component_xml(exec_command: str) -> str:
    """Component XML that makes 'rechka' discoverable by GNOME Settings.

    GNOME Control Center lists the engines reported by
    ibus_bus_list_engines(), which the daemon fills from component XML
    (its `engine_table`), not from runtime-registered components (those
    only appear in list_active_engines()).  Without this file Rechka can
    never be selected as an input source in Settings.
    """
    esc = escape
    return f"""<?xml version="1.0" encoding="utf-8"?>
<component>
  <name>{IBUS_COMPONENT_NAME}</name>
  <description>Rechka voice dictation</description>
  <exec>{esc(exec_command)}</exec>
  <version>{esc(__version__)}</version>
  <author>Rechka</author>
  <license>MIT</license>
  <homepage></homepage>
  <textdomain>rechka</textdomain>
  <engines>
    <engine>
      <name>{IBUS_ENGINE_NAME}</name>
      <longname>Rechka</longname>
      <description>Rechka offline voice dictation (Russian)</description>
      <language>ru</language>
      <license>MIT</license>
      <author>Rechka</author>
      <icon>audio-input-microphone-symbolic</icon>
      <layout>default</layout>
      <rank>0</rank>
    </engine>
  </engines>
</component>
"""


def _ibus_dropin_text(component_dir: Path) -> str:
    # IBUS_COMPONENT_PATH *replaces* the search path when set (the user
    # directory is not scanned by default), so keep the system directory
    # and any directories the user already had.
    dirs: list[str] = []
    for raw in (
        str(_SYSTEM_COMPONENT_DIR),
        str(component_dir),
        *os.environ.get("IBUS_COMPONENT_PATH", "").split(":"),
    ):
        if raw and raw not in dirs:
            dirs.append(raw)
    value = ":".join(dirs)
    # --cache none matters on Fedora: its ibus package maintains a
    # system registry cache (/var/cache/ibus/bus/registry) which the
    # daemon, in the default --cache auto mode, loads *instead of*
    # scanning IBUS_COMPONENT_PATH whenever the system XML is unchanged
    # — a per-user engine would stay invisible.  Scanning the XML on
    # each start is cheap and always current.  The ExecStart otherwise
    # mirrors the vendor GNOME unit.
    return (
        "[Service]\n"
        "Environment=\n"
        f'Environment="IBUS_COMPONENT_PATH={value}"\n'
        "ExecStart=\n"
        "ExecStart=sh -c 'exec /usr/bin/ibus-daemon --panel disable "
        "--cache none $([ \"$XDG_SESSION_TYPE\" = \"x11\" ] && echo \"--xim\")'\n"
    )


def install_ibus_component(
    cfg: Config, *, exec_start: str | None = None, system: bool = False
) -> IBusInstallResult:
    """Install the component XML (and, per-user, the systemd drop-in).

    Per-user installs also write the distro-Python launcher the XML
    points at and a systemd user drop-in that puts the user component
    directory on IBUS_COMPONENT_PATH for the GNOME IBus service (IBus
    does not scan ~/.local/share/ibus/component by default).
    """
    component_dir = ibus_component_dir(system)
    component_dir.mkdir(parents=True, exist_ok=True)
    launcher: Path | None = None
    if exec_start:
        exec_command = exec_start
    else:
        launcher = write_ibus_launcher()
        argv = [str(launcher)]
        if cfg.source is not None:
            argv.append(str(cfg.source))
        exec_command = shlex.join(argv)
    component_path = ibus_component_path(system)
    component_path.write_text(component_xml(exec_command), encoding="utf-8")
    dropin: Path | None = None
    if not system:
        dropin = ibus_dropin_path()
        dropin.parent.mkdir(parents=True, exist_ok=True)
        dropin.write_text(_ibus_dropin_text(component_dir), encoding="utf-8")
    return IBusInstallResult(component_path, launcher, dropin, exec_command)


def uninstall_ibus_component(*, system: bool = False) -> list[Path]:
    targets = [ibus_component_path(system)]
    if not system:
        targets += [ibus_dropin_path(), ibus_launcher_path()]
    removed: list[Path] = []
    for target in targets:
        try:
            target.unlink()
        except FileNotFoundError:
            continue
        removed.append(target)
    return removed


# -- GNOME input-source list (the Super+Space switcher) -------------------
#
# GNOME's switcher cycles `org.gnome.desktop.input-sources sources`. That
# list is a Shell UI concept only: the IBus daemon activates any engine
# from its component registry (set-global-engine, which the daemon's
# auto-switch drives) whether or not GNOME lists it. Since dictation
# start/stop already switches to Rechka and back, Rechka needs no
# permanent slot in the switcher — these helpers add/remove it there.

_GNOME_INPUT_SOURCES_SCHEMA = "org.gnome.desktop.input-sources"
_GNOME_SOURCE_KEYS = ("sources", "mru-sources")


@dataclass
class GnomeSourceListResult:
    ok: bool
    detail: str


def parse_gnome_sources(raw: str) -> list[tuple[str, str]] | None:
    """Parse a gsettings `sources` value; None when it is not that shape."""
    try:
        value = ast.literal_eval(raw.strip())
    except (ValueError, SyntaxError):
        return None
    if not isinstance(value, list):
        return None
    result: list[tuple[str, str]] = []
    for item in value:
        if (
            isinstance(item, tuple)
            and len(item) == 2
            and all(isinstance(part, str) for part in item)
        ):
            result.append((item[0], item[1]))
        else:
            return None
    return result


def format_gnome_sources(sources: list[tuple[str, str]]) -> str:
    return "[" + ", ".join(f"('{kind}', '{name}')" for kind, name in sources) + "]"


def set_gnome_engine_listed(
    engine_name: str,
    *,
    listed: bool,
    runner: Callable[..., "subprocess.CompletedProcess[str]"] | None = None,
) -> GnomeSourceListResult:
    """Add/remove ('ibus', <engine>) in GNOME's input-source lists.

    Touches `sources` and `mru-sources` via gsettings. Best-effort and
    never raises: on a non-GNOME session it just reports that. The IBus
    component registration is not affected either way — the engine stays
    installed and programmatically switchable.
    """
    run = runner or (
        lambda argv: subprocess.run(argv, capture_output=True, text=True, check=False)
    )
    if runner is None and shutil.which("gsettings") is None:
        return GnomeSourceListResult(
            False, "gsettings not found; this does not look like a GNOME session."
        )
    entry = (FRAMEWORK_IBUS, engine_name)
    changed: list[str] = []
    for key in _GNOME_SOURCE_KEYS:
        try:
            got = run(["gsettings", "get", _GNOME_INPUT_SOURCES_SCHEMA, key])
        except OSError as exc:
            return GnomeSourceListResult(False, f"could not run gsettings: {exc}")
        if got.returncode != 0:
            detail = (got.stderr or "").strip()
            return GnomeSourceListResult(
                False,
                f"gsettings get {key} failed{': ' + detail if detail else ''}; "
                "is this a GNOME session?",
            )
        sources = parse_gnome_sources(got.stdout or "")
        if sources is None:
            return GnomeSourceListResult(
                False, f"could not parse the gsettings {key} value: {got.stdout!r}"
            )
        if listed:
            updated = list(sources) if entry in sources else [*sources, entry]
        else:
            updated = [item for item in sources if item != entry]
        if updated == sources:
            continue
        try:
            put = run(
                [
                    "gsettings",
                    "set",
                    _GNOME_INPUT_SOURCES_SCHEMA,
                    key,
                    format_gnome_sources(updated),
                ]
            )
        except OSError as exc:
            return GnomeSourceListResult(False, f"could not run gsettings: {exc}")
        if put.returncode != 0:
            detail = (put.stderr or "").strip()
            return GnomeSourceListResult(
                False, f"gsettings set {key} failed{': ' + detail if detail else ''}"
            )
        changed.append(key)
    if listed:
        detail = (
            "Rechka added to the GNOME input-source list; it appears in the "
            "switcher again."
            if changed
            else "Rechka is already in the GNOME input-source list."
        )
    else:
        detail = (
            "Rechka removed from the GNOME input-source list; it no longer "
            "appears in the switcher. The daemon still activates it while "
            "dictating and switches back on stop."
            if changed
            else "Rechka is not in the GNOME input-source list; nothing to change."
        )
    return GnomeSourceListResult(True, detail)


class EngineUnavailableError(RuntimeError):
    pass


def engine_socket_path(framework: str) -> Path:
    from .engine_server import engine_socket_path as _path

    return _path(framework)


class EngineClient:
    """Client for a running engine process (see engine_server.py)."""

    def __init__(self, framework: str):
        self.framework = framework
        self.socket_path = engine_socket_path(framework)

    def request(self, payload: dict, timeout: float = 10.0) -> dict:
        import socket as socket_module

        sock = socket_module.socket(socket_module.AF_UNIX, socket_module.SOCK_STREAM)
        sock.settimeout(timeout)
        try:
            sock.connect(str(self.socket_path))
        except OSError as exc:
            raise EngineUnavailableError(
                f"{self.framework} engine is not reachable at {self.socket_path}"
            ) from exc
        try:
            sock.sendall((json.dumps(payload) + "\n").encode("utf-8"))
            chunks: list[bytes] = []
            while True:
                data = sock.recv(65536)
                if not data:
                    break
                chunks.append(data)
                if b"\n" in data:
                    break
        finally:
            sock.close()
        lines = b"".join(chunks).splitlines()
        if not lines:
            raise EngineUnavailableError(f"Empty response from {self.framework} engine")
        return json.loads(lines[0].decode("utf-8"))

    def ping(self) -> dict:
        return self.request({"cmd": "ping"}, timeout=3.0)

    def commit(self, text: str) -> dict:
        return self.request({"cmd": "commit", "text": text}, timeout=30.0)

    def shutdown(self) -> dict:
        return self.request({"cmd": "shutdown"}, timeout=3.0)


def _python_candidates() -> list[str]:
    candidates: list[str] = []
    for raw in (sys.executable, "/usr/bin/python3", shutil.which("python3")):
        if raw and raw not in candidates:
            candidates.append(raw)
    return candidates


def _python_has_ibus(executable: str) -> bool:
    if os.path.abspath(executable) == os.path.abspath(sys.executable):
        try:
            import gi

            gi.require_version("IBus", "1.0")
            from gi.repository import IBus  # noqa: F401
        except Exception:
            return False
        return True
    try:
        result = subprocess.run(
            [executable, "-c", _GI_PROBE],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=5,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    return result.returncode == 0


def _ibus_python() -> str | None:
    for candidate in _python_candidates():
        if _python_has_ibus(candidate):
            return candidate
    return None


_IBUS_MISSING_DETAIL = (
    "IBus bindings unavailable in rechka's Python and in distro "
    "python3; Fedora: `sudo dnf install python3-gobject ibus-libs`; "
    "Debian/Ubuntu: `sudo apt install python3-gi gir1.2-ibus-1.0`; "
    "or run rechka with PyGObject in its own environment "
    "(`uv run --extra ibus rechka serve` / `--with PyGObject`)"
)


def engine_prerequisites(framework: str) -> tuple[bool, str]:
    """Can this framework's engine run here? (bool, human detail)."""
    if framework == FRAMEWORK_NONE:
        return False, "no input-method framework in use"
    if framework == FRAMEWORK_FCITX5:
        return True, "typing engine (ydotool/wtype/xdotool chosen per commit)"
    # IBus: the engine is a PyGObject process.  rechka's own Python is
    # preferred, but the engine only needs the stdlib, so a distro
    # python3 with the bindings is just as good (see _ibus_engine_command).
    python = _ibus_python()
    if python is None:
        return False, _IBUS_MISSING_DETAIL
    if not os.environ.get("DBUS_SESSION_BUS_ADDRESS"):
        return False, "no D-Bus session (DBUS_SESSION_BUS_ADDRESS is not set)"
    if os.path.abspath(python) == os.path.abspath(sys.executable):
        return True, "IBus engine (PyGObject)"
    return True, f"IBus engine (distro Python fallback: {python})"


def _ibus_engine_command(cfg: Config) -> tuple[list[str] | None, str]:
    """Command that runs the IBus engine with a Python that has the bindings."""
    python = _ibus_python()
    if python is None:
        return None, _IBUS_MISSING_DETAIL
    if os.path.abspath(python) == os.path.abspath(sys.executable):
        argv = [sys.executable, "-m", "rechka", "im-engine", "ibus"]
        if cfg.source is not None:
            argv += ["--config", str(cfg.source)]
        return argv, "IBus engine (PyGObject)"
    # Run the engine under the distro Python, which is where the distro
    # PyGObject/IBus packages live; the uv venv stays free of them.  A
    # generated launcher puts this same package on that Python's path.
    launcher = write_ibus_launcher(
        engine_socket_path(FRAMEWORK_IBUS).parent / "ibus-launcher.py",
        exec_by_ibus=False,
    )
    argv = [python, str(launcher)]
    if cfg.source is not None:
        argv.append(str(cfg.source))
    return argv, f"IBus engine (distro Python fallback: {python})"


def start_engine(framework: str, cfg: Config) -> EngineStatus:
    """Start the framework's engine process (unless one already runs).

    Never raises: failures come back as EngineStatus(started=False) so
    the daemon can log the reason and keep serving without IM output.
    """
    if framework == FRAMEWORK_NONE:
        return EngineStatus(framework, False, "no input-method framework in use; skipped")
    ok, detail = engine_prerequisites(framework)
    if not ok:
        return EngineStatus(framework, False, detail)

    client = EngineClient(framework)
    try:
        client.ping()
        return EngineStatus(framework, True, "engine already running")
    except EngineUnavailableError:
        pass

    if framework == FRAMEWORK_IBUS:
        argv, detail = _ibus_engine_command(cfg)
        if argv is None:
            return EngineStatus(framework, False, detail)
    else:
        argv = [sys.executable, "-m", "rechka", "im-engine", framework]
        if cfg.source is not None:
            argv += ["--config", str(cfg.source)]
    try:
        process = subprocess.Popen(
            argv,
            stdin=subprocess.DEVNULL,
            start_new_session=True,
        )
    except OSError as exc:
        return EngineStatus(framework, False, f"cannot spawn engine: {exc}")

    deadline = time.monotonic() + 8.0
    while time.monotonic() < deadline:
        if process.poll() is not None:
            return EngineStatus(
                framework,
                False,
                f"engine exited with code {process.returncode} during startup; "
                "run `rechka im-engine " + framework + "` in a terminal for details",
            )
        try:
            client.ping()
            return EngineStatus(
                framework, True, f"{detail}; engine running", pid=process.pid,
                process=process,
            )
        except EngineUnavailableError:
            time.sleep(0.1)
    process.terminate()
    return EngineStatus(framework, False, "engine did not answer on its socket in 8 s")


def stop_engine(status: EngineStatus | None) -> None:
    """Ask an engine we started to exit (best effort, never raises)."""
    if status is None or not status.started:
        return
    process = status.process
    if process is None:
        # Already running when we looked (e.g. started by ibus-daemon
        # from the installed component): not ours to shut down.
        return
    try:
        EngineClient(status.framework).shutdown()
    except EngineUnavailableError:
        pass
    if process is not None:
        try:
            process.wait(timeout=3)
        except Exception:
            try:
                process.terminate()
            except Exception:
                pass


def get_current_ibus_engine() -> str | None:
    """Current IBus global engine name (e.g. 'xkb:us::eng'), or None.

    Uses the `ibus` CLI, which is the supported command-line interface
    for getting/setting the global engine; it returns None when IBus or
    the CLI is unavailable or no global engine is set.
    """
    executable = shutil.which("ibus")
    if executable is None:
        return None
    try:
        result = subprocess.run(
            [executable, "engine"],
            text=True,
            capture_output=True,
            timeout=3,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    lines = [line.strip() for line in result.stdout.splitlines() if line.strip()]
    if not lines:
        return None
    name = lines[0]
    if "no engine" in name.lower():
        return None
    return name


def set_current_ibus_engine(engine_name: str) -> bool:
    """Set the IBus global engine; False when the switch did not happen.

    The exit code of `ibus engine <name>` alone is not proof: the CLI
    may return non-zero for follow-up work (e.g. setxkbmap) after the
    engine was in fact switched. Verify by reading the engine back.
    """
    executable = shutil.which("ibus")
    if executable is None:
        return False
    try:
        result = subprocess.run(
            [executable, "engine", engine_name],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=5,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    deadline = time.monotonic() + 2.0
    while time.monotonic() < deadline:
        if get_current_ibus_engine() == engine_name:
            return True
        time.sleep(0.1)
    return result.returncode == 0


@dataclass
class IBusSwitchResult:
    ok: bool
    detail: str
    current: str | None = None
    previous: str | None = None


class IBusEngineSwitcher:
    """Temporarily switch the session to the Rechka IBus engine.

    activate() remembers the engine that was current when dictation
    started and switches to 'rechka'. restore() switches back, unless
    the user has meanwhile chosen a different input themselves — their
    manual choice is never overridden. Failures are reported as results,
    not exceptions: dictation must keep working (text simply queues)
    even when the switch cannot be performed.
    """

    def __init__(
        self,
        *,
        get_current: Callable[[], str | None] = get_current_ibus_engine,
        set_current: Callable[[str], bool] = set_current_ibus_engine,
    ):
        self._get_current = get_current
        self._set_current = set_current
        self._lock = threading.Lock()
        self._previous: str | None = None
        self._active = False

    @property
    def active(self) -> bool:
        with self._lock:
            return self._active

    @property
    def previous(self) -> str | None:
        with self._lock:
            return self._previous

    def activate(self) -> IBusSwitchResult:
        with self._lock:
            current = self._safe_current()
            if current == IBUS_ENGINE_NAME:
                return IBusSwitchResult(
                    True,
                    "Rechka input already active",
                    current=current,
                    previous=self._previous,
                )
            if self._active:
                return IBusSwitchResult(
                    True,
                    "Rechka input already switched",
                    current=current,
                    previous=self._previous,
                )
            previous = current
            if not self._safe_set(IBUS_ENGINE_NAME):
                return IBusSwitchResult(
                    False,
                    "could not switch the system input to Rechka "
                    "(is the Rechka IBus engine installed/selected?)",
                    current=current,
                    previous=previous,
                )
            self._previous = previous
            self._active = True
            return IBusSwitchResult(
                True,
                f"switched input to Rechka (was {previous or 'unset'})",
                current=IBUS_ENGINE_NAME,
                previous=previous,
            )

    def restore(self) -> IBusSwitchResult:
        with self._lock:
            if not self._active:
                return IBusSwitchResult(True, "input was not switched by Rechka")
            previous = self._previous
            if previous is None:
                self._active = False
                return IBusSwitchResult(
                    True,
                    "no previous input to restore; leaving Rechka active",
                    current=IBUS_ENGINE_NAME,
                )
            current = self._safe_current()
            if current not in (None, IBUS_ENGINE_NAME):
                self._active = False
                self._previous = None
                return IBusSwitchResult(
                    True,
                    f"input was changed manually to {current}; leaving it there",
                    current=current,
                    previous=previous,
                )
            if not self._safe_set(previous):
                return IBusSwitchResult(
                    False,
                    f"could not switch input back to {previous}",
                    current=current,
                    previous=previous,
                )
            self._active = False
            self._previous = None
            return IBusSwitchResult(
                True,
                f"switched input back to {previous}",
                current=previous,
                previous=previous,
            )

    def _safe_current(self) -> str | None:
        try:
            return self._get_current()
        except Exception:
            return None

    def _safe_set(self, engine_name: str) -> bool:
        try:
            return bool(self._set_current(engine_name))
        except Exception:
            return False
