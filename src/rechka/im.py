"""Input-method framework integration (IBus primary, Fcitx5 secondary).

This module owns:
- detecting which framework the current desktop session actually uses, so
  the daemon starts the matching engine and only that one;
- the engine lifecycle: start_engine spawns `rechka im-engine <framework>`
  (ibus_engine.py — a real PyGObject IBus engine; fcitx5_engine.py — a
  typing engine, see its docstring) and EngineClient talks to it over the
  engine socket (engine_server.py). Starting never raises: a desktop
  without a usable engine must not take the daemon down.
"""

